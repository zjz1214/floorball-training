const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {status,review,commit,pushPlan,push}=require('./github.cjs');

test('reviews selected files, protects existing staged changes and pushes only a reviewed commit',async()=>{
  const cache=path.resolve(__dirname,'../.vitepress/cache/content-editor');
  await fs.mkdir(cache,{recursive:true});
  const dir=await fs.mkdtemp(path.join(cache,'github-test-'));
  const remote=path.join(dir,'remote.git');
  const root=path.join(dir,'project');
  const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8',windowsHide:true}).trim();
  await fs.mkdir(root);
  git('init','-q','-b','main');
  git('init','--bare','-q',remote);
  git('config','user.name','Desktop QA');
  git('config','user.email','test@example.invalid');
  const write=(name,text)=>fs.writeFile(path.join(root,name),text);
  await write('index.md','# 原始内容\n');
  await write('app.js','old\n');
  git('add','.');git('commit','-qm','Initial');
  git('remote','add','origin',remote);git('push','-q','origin','main');
  await write('index.md','# 更新内容\n');
  await write('app.js','staged\n');git('add','app.js');
  await write('新文件.md','# 新页面\n');
  await write('.env','example=placeholder\n');
  assert.equal((await status(root)).files.find(file=>file.name==='.env').policy,'blocked');
  await assert.rejects(review(root,'.env'));
  const credentials=async name=>({name,...await review(root,name)});
  const stale=await credentials('index.md');
  assert.match(stale.diff,/更新内容/);
  await write('index.md','# 再次更新\n');
  await assert.rejects(commit(root,[stale],'过期提交'),/已变化/);
  const added=await credentials('新文件.md');
  assert.match(added.diff,/新页面/);
  await commit(root,[await credentials('index.md'),added],'更新训练内容');
  assert.equal(git('diff','--cached','--name-only'),'app.js');
  assert.equal(git('show','HEAD:app.js'),'old');
  assert.equal(git('show','HEAD:index.md'),'# 再次更新');
  await assert.rejects(pushPlan(root),/GitHub/);
  const localFixture=value=>{assert.equal(path.resolve(value),remote);return value;};
  const plan=await pushPlan(root,localFixture);
  assert.match(plan.commits,/更新训练内容/);
  await assert.rejects(push(root,{...plan,head:plan.base},localFixture),/已变化/);
  assert.equal(await push(root,plan,localFixture),true);
  assert.equal(git('--git-dir='+remote,'rev-parse','main'),git('rev-parse','HEAD'));
  assert.equal((await pushPlan(root,localFixture)).commits,'');
});
